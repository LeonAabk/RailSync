async function initializeApplet() {
  applyDesign(currentDesign()); // dispatch.js har satt designet; her følger fargen på nettleserlinjen og velgeren med
  await loadAppState();
  // Kartet (Leaflet) lages først når brukeren er logget inn – se ensureMap() i 06-kart.js
  renderAll();
  setOverviewView("stops", { keepMap: true });
  updateInstallItems();
  setupNominatimSearch();
  setupLiveTrainSearch();
  if (window.lucide) {
    lucide.createIcons();
  }
  // Automatically enrich any trains missing real track geometry in the background
  setTimeout(() => {
    fetchRealTracksForAllTrains(true);
  }, 800);
  // Hent valutakurser i bakgrunnen, så de finnes også uten nett på reisen
  setTimeout(() => {
    const foreign = (appState.stops || []).some(st => { const c = countryInfoFor(st.country); return c && c.currency !== "NOK"; });
    if (foreign) ensureFxRates().then(() => { if (currentTab === "budget") renderFxCalculator(); });
  }, 2500);
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initializeApplet);
} else {
  initializeApplet();
}
